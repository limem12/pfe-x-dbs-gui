// ── Type helpers ───────────────────────────────────────────
type TranslationLeaf = { fr: string; en: string }
type TranslationNode = { [key: string]: TranslationLeaf | TranslationNode }

function isLeaf(node: TranslationLeaf | TranslationNode): node is TranslationLeaf {
  return typeof (node as TranslationLeaf).fr === "string"
}

export function t(
  locale: Locale,
  section: keyof typeof translations,
  key: string
): string {
  const sec = translations[section] as TranslationNode
  const node = sec[key]
  if (!node) return key
  if (isLeaf(node)) return node[locale]
  return key
}
